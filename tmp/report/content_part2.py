            ["Tác nhân chính", primary],
            ["Tác nhân phụ", secondary],
            ["Đối tượng liên quan và lợi ích", stakes],
            ["Mô tả ngắn (Brief Description)", brief],
            ["Điều kiện tiên quyết (Preconditions)", pre],
            ["Điều kiện cuối (Postconditions)", post],
            ["Dẫn sự kiện (Triggers)", trigger],
            ["Tần suất (Frequency)", freq],
            ["Điều kiện giả định (Assumptions)", assum],
            ["Điều kiện kết thúc thất bại (Failure Conditions)", fail],
